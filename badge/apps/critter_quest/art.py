# Original pixel art for Critter Quest. Every sprite is drawn with the four
# shades of the handheld-style yellow palette: 0 = lightest .. 3 = darkest,
# "." = transparent.

PALETTE = (
    (248, 240, 200),
    (232, 192, 64),
    (152, 100, 36),
    (40, 28, 16),
)
PENS = [color.rgb(*rgb) for rgb in PALETTE]


def sym(halves):
    return [h + "".join(reversed(h)) for h in halves]


def tile8(rows):
    rows = [r + r for r in rows]
    return rows + rows


def make(rows, size=16):
    if len(rows) != size:
        raise ValueError("sprite needs %d rows, got %d" % (size, len(rows)))
    sprite = image(size, size)
    sprite.antialias = image.OFF
    sprite.pen = color.rgb(0, 0, 0, 0)
    sprite.clear()
    for y, row in enumerate(rows):
        row = (row + "." * size)[:size]
        for x, ink in enumerate(row):
            if ink != ".":
                sprite.pen = PENS[ord(ink) - 48]
                sprite.put(x, y)
    return sprite


